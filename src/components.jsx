// —— Button ——
function Button({ variant = 'primary', size, icon, children, ...rest }) {
  const cls = `btn btn-${variant}${size ? ' btn-' + size : ''}`;
  return (
    <button className={cls} {...rest}>
      {icon && <span style={{ display: 'inline-flex' }}>{icon}</span>}
      {children}
    </button>
  );
}

// —— Badge para estados ——
function StatusBadge({ value }) {
  const map = {
    'Activo': 'green', 'Pagado': 'green',
    'Pendiente': 'amber', 'Reservado': 'amber', 'Tardanza': 'amber',
    'Vencido': 'red', 'Moroso': 'red', 'Falta': 'red',
    'Suspendido': 'neutral',
    'Disponible': 'blue',
    'Ocupado': 'green',
    'Justificado': 'blue',
    'Presente': 'green',
  };
  return <span className={`badge ${map[value] || 'neutral'}`}>{value}</span>;
}

