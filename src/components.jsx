// —— Modal ——
function Modal({ open, onClose, title, children, foot, size }) {
  if (!open) return null;
  return (
    <div className="modal-bg" onClick={onClose}>
      <div className={`modal ${size === 'lg' ? 'modal-lg' : ''}`} onClick={e => e.stopPropagation()}>
        <div className="modal-head">
          <div className="modal-title">{title}</div>
          <button className="icon-btn" onClick={onClose} style={{ width: 30, height: 30 }}><Icon.close /></button>
        </div>
        <div className="modal-body">{children}</div>
        {foot && <div className="modal-foot">{foot}</div>}
      </div>
    </div>
  );
}

// —— Toast ——
function useToasts() {
  const [toasts, setToasts] = React.useState([]);
  const push = React.useCallback((text, kind = 'success') => {
    const id = Date.now() + Math.random();
    setToasts(t => [...t, { id, text, kind }]);
    setTimeout(() => setToasts(t => t.filter(x => x.id !== id)), 3000);
  }, []);
  const node = (
    <div className="toast-container">
      {toasts.map(t => (
        <div key={t.id} className={`toast ${t.kind}`}>
          {t.kind === 'success' && <Icon.check />}
          {t.kind === 'error' && <Icon.alert />}
          <span>{t.text}</span>
        </div>
      ))}
    </div>
  );
  return [push, node];
}

// —— Pagination component ——
function Pagination({ page, pageSize, total, onChange }) {
  const totalPages = Math.max(1, Math.ceil(total / pageSize));
  const from = total === 0 ? 0 : (page - 1) * pageSize + 1;
  const to = Math.min(total, page * pageSize);
  const buildPages = () => {
    const out = [];
    const max = 7;
    if (totalPages <= max) {
      for (let i = 1; i <= totalPages; i++) out.push(i);
    } else {
      out.push(1);
      let s = Math.max(2, page - 2);
      let e = Math.min(totalPages - 1, page + 2);
      if (s > 2) out.push('…');
      for (let i = s; i <= e; i++) out.push(i);
      if (e < totalPages - 1) out.push('…');
      out.push(totalPages);
    }
    return out;
  };
  return (
    <div className="pagination">
      <div>Mostrando <b style={{ color: 'var(--ink)' }}>{from}–{to}</b> de <b style={{ color: 'var(--ink)' }}>{fmtNum(total)}</b></div>
      <div className="pag-pages">
        <button className="pag-btn" disabled={page <= 1} onClick={() => onChange(page - 1)}><Icon.chevronleft /></button>
        {buildPages().map((p, i) => (
          p === '…'
            ? <span key={i} className="pag-btn" style={{ border: 'none', background: 'transparent', cursor: 'default' }}>…</span>
            : <button key={i} className={`pag-btn ${p === page ? 'active' : ''}`} onClick={() => onChange(p)}>{p}</button>
        ))}
        <button className="pag-btn" disabled={page >= totalPages} onClick={() => onChange(page + 1)}><Icon.chevronright /></button>
      </div>
    </div>
  );
}

// —— Sparkline (mini chart for KPI cards) ——
function Sparkline({ data, color }) {
  if (!data || data.length < 2) return null;
  const w = 80, h = 36;
  const max = Math.max(...data), min = Math.min(...data);
  const range = max - min || 1;
  const pts = data.map((v, i) => {
    const x = (i / (data.length - 1)) * w;
    const y = h - ((v - min) / range) * h;
    return `${x.toFixed(1)},${y.toFixed(1)}`;
  }).join(' ');
  return (
    <svg viewBox={`0 0 ${w} ${h}`} className="kpi-spark" preserveAspectRatio="none">
      <polyline points={pts} fill="none" stroke={color || 'var(--primary)'} strokeWidth="1.5" strokeLinecap="round" strokeLinejoin="round" />
    </svg>
  );
}

